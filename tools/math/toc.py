def sid(num):
    return 'ma-' + num.replace('.', '-')

def ranges():
    """Страницы пункта: от его первой страницы до страницы, где начинается следующий пункт того же или
    более высокого уровня (на ней пункт обычно заканчивается); последний пункт части — до конца части."""
    out = []
    for i, (num, title, p) in enumerate(TOC):
        top = num.split('.')[0]
        depth = num.count('.')
        end = LAST_PAGE[int(top)]
        for num2, _, p2 in TOC[i + 1:]:
            if num2.split('.')[0] != top:
                break
            if num2.count('.') <= depth or depth == 2:
                end = max(p, p2)
                break
        out.append((num, title, p, end))
    return out

def items():
    """Пункты — темы: три уровня, а также главы без пунктов (1.18, 3.1, 3.2, 3.5, 3.8, 3.10)."""
    rows = ranges()
    chapters = [r for r in rows if r[0].count('.') == 1]
    res = []
    for ch in chapters:
        subs = [r for r in rows if r[0].startswith(ch[0] + '.') and r[0].count('.') == 2]
        if subs:
            for r in subs:
                res.append((ch[0], r))
        else:
            res.append((ch[0], ch))
    return chapters, res

if __name__ == '__main__':
    chapters, res = items()
    print('subsections:')
    for num, title, p, end in chapters:
        sec = 'ma-alg' if num.startswith('1.') else 'ma-geo'
        note = NOTES.get(num)
        n = f", note: '{note}'" if note else ''
        print(f"  - {{ id: {sid(num)}, sectionId: {sec}, title: '{num} {title}'{n} }}")
    print('plan:')
    for ch, (num, title, p, end) in res:
        pages = ', '.join(f'b{n:03d}' for n in range(p, end + 1))
        note = MIXED.get(num) or (NOTES.get(num) if num.count('.') == 1 else None)
        n = f", note: '{note}'" if note else ''
        print(f"  - {{ num: '{num}', subsectionId: {sid(ch)}, title: '{title}', pages: [{pages}]{n} }}")
