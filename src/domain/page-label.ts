// Короткая подпись страницы-источника для интерфейса.
// Префикс ссылки — исходный файл: p — механика (p05L → «5L»), m — молекулярная физика (m07 → «м7»),
// h — фото «Влажность воздуха» (h01 → «вл1»), c — электричество (c05 → «эл5»), e — магнетизм и колебания (e05 → «мг5»),
// o — оптика (o12 → «оп12»), d — фото «Дифракция» (d01 → «дф1»), a — атомная и ядерная физика (a05 → «ат5»).
// Математика: b — печатная страница книги «Математика. Сборник тестовых заданий» (b157 → «157»; нумерация
// сквозная для обеих частей).
const PREFIX_LABEL: Record<string, string> = { p: '', m: 'м', h: 'вл', c: 'эл', e: 'мг', o: 'оп', d: 'дф', a: 'ат', b: '' };

export function pageLabel(ref: string): string {
  const m = /^([a-z])(\d+)([LR]?)$/.exec(ref);
  if (!m) return ref;
  return `${PREFIX_LABEL[m[1]] ?? m[1]}${Number(m[2])}${m[3]}`;
}

/** Заменяет в обычном тексте ссылки вида «стр. c03», «e10–e11» на подписи интерфейса («эл3», «мг10–мг11»),
 *  чтобы подсказки и пояснения совпадали с подписями источников (p11L → «11L»). */
export function labelPageRefs(text: string): string {
  return text.replace(/\b([mhceoda])(\d{2})([LR]?)\b|\bp(\d{2})([LR])\b/g, (ref) => pageLabel(ref));
}
